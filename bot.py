@app.route('/register_or_login', methods=['POST'])
def register_or_login():
    data = request.json or {}
    init_data = data.get('initData', '')
    raw_phone = sanitize_input(data.get('phone', ''))

    # ከContact Sharing የሚመጣውን ስልክ ቁጥር በBackend በጥብቅ ማረጋገጥ (ከinitData ጋር አብሮ የሚመጣውን የተጠቃሚ መለያ በመፈተሽ)
    validated_user = validate_telegram_init_data(init_data)
    if not validated_user:
        return jsonify({"success": False, "msg": "የቴሌግራም ማረጋገጫ (initData) አልተሳካም!"}), 400

    telegram_id = str(validated_user.get('id'))
    first_name = validated_user.get('first_name', 'User')
    username = validated_user.get('username', f"User_{telegram_id[-4:]}")

    # የስልክ ቁጥር Format ማስተካከያ (ወደ 2519xxxxxxxx መቀየር)
    clean_phone = raw_phone.replace("+", "").replace(" ", "")
    if clean_phone.startswith("09") or clean_phone.startswith("07"):
        clean_phone = "251" + clean_phone[1:]
    elif clean_phone.startswith("9") or clean_phone.startswith("7"):
        clean_phone = "251" + clean_phone

    # Unique Phone Constraint: አንድ ስልክ ቁጥር ዳታቤዝ ውስጥ አንዴ ከተመዘገበ በኋላ ለሌላ Telegram ID ደግመው እንዳይመዘገቡ መከላከል
    existing_phone = wallets.find_one({"phone": clean_phone})
    if existing_phone and str(existing_phone.get("telegram_id")) != telegram_id:
        return jsonify({"success": False, "msg": "ይህ ስልክ ቁጥር ከሌላ የቴሌግራም መለያ ጋር ተመዝግቧል!"}), 400

    update_doc = {
        "$set": {
            "first_name": first_name,
            "username": username,
            "phone": clean_phone,
            "status": "ACTIVE"
        },
        "$setOnInsert": {
            "telegram_id": telegram_id,
            "balance": 20.00,
            "created_at": datetime.utcnow()
        }
    }

    wallets.update_one({"telegram_id": telegram_id}, update_doc, upsert=True)
    user_record = wallets.find_one({"telegram_id": telegram_id})

    return jsonify({
        "success": True,
        "telegram_id": telegram_id,
        "first_name": first_name,
        "username": username,
        "balance": user_record.get("balance", 20.00),
        "status": user_record.get("status", "ACTIVE")
    })

